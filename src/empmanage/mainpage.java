    //add to database
    public void addtodb(JTable jt){
        DefaultTableModel db=(DefaultTableModel)jt.getModel();
        
        if(db.getRowCount()==0){
            JOptionPane.showMessageDialog(this, "Input Employee Details", "No Input Found", JOptionPane.WARNING_MESSAGE);
        }else{
            try{
                            
                Connection con=DriverManager.getConnection("jdbc:mysql://localhost:3306/dt","root","");
                int addedc=0;
                
                String msg="insert into details values(?,?,?,?)";
                PreparedStatement pst=con.prepareStatement(msg);
                for(int i=0;i<db.getRowCount();i++){
                     String  id=db.getValueAt(i, 0).toString();
                     String  n=db.getValueAt(i, 1).toString();
                     String  d=db.getValueAt(i, 2).toString();
                     String  s=db.getValueAt(i, 3).toString();
                    
                     if(checkForExisting(id)){
                         JOptionPane.showMessageDialog(this, "Employee ID " + id + " already exists!", "Duplicate Entry", JOptionPane.WARNING_MESSAGE);
                         
                         continue;
                     }
                     pst.setString(1, id);
                     pst.setString(2, n);
                     pst.setString(3, d);
                     pst.setString(4, s);
                     pst.execute();  
                     addedc++;
                     
                }
                if(addedc>0){
                    adddedlabel.setText(Integer.toString(addedc));
                    //JOptionPane.showMessageDialog(this, "Succesfully Added To Database", "Database Info", JOptionPane.INFORMATION_MESSAGE);
                    db.setRowCount(0);
                }
            }catch(Exception e){System.out.print(e);}
        }
    }
